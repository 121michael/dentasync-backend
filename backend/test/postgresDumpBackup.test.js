"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const test = require("node:test");
const { Client, Pool } = require("pg");
const { applyAdminBackupSchema } = require("../services/backupSchema");
const { createBackupRecoveryService } = require("../services/backupRecovery");
const { assertSeparateDatabase } = require("../services/backupPgCustom");

const DB_NAME = "dentasync_dump_src";
const baseEnv = {
  DB_HOST: process.env.DB_HOST || "127.0.0.1",
  DB_PORT: process.env.DB_PORT || "5432",
  DB_USER: process.env.DB_USER || "postgres",
  DB_PASSWORD: process.env.DB_PASSWORD || "postgres",
  DB_NAME,
  DATABASE_SSL: "disable",
  BACKUP_SKIP_PG_DUMP: "true",
  BACKUP_ALLOW_PRODUCTION_RESTORE: "false",
};

function adminClient(database) {
  return new Client({
    host: baseEnv.DB_HOST,
    port: Number(baseEnv.DB_PORT),
    user: baseEnv.DB_USER,
    password: baseEnv.DB_PASSWORD,
    database,
  });
}

async function postgresReady() {
  const client = adminClient("postgres");
  try {
    await client.connect();
    await client.query("SELECT 1");
    return true;
  } catch {
    return false;
  } finally {
    await client.end().catch(() => {});
  }
}

test("PostgreSQL custom dump backup and recovery", { timeout: 180000 }, async (t) => {
  if (!(await postgresReady())) {
    t.skip("Local PostgreSQL is not available.");
    return;
  }

  const maint = adminClient("postgres");
  await maint.connect();
  await maint.query(
    `SELECT pg_terminate_backend(pid)
     FROM pg_stat_activity
     WHERE datname = $1 AND pid <> pg_backend_pid()`,
    [DB_NAME]
  );
  await maint.query(`DROP DATABASE IF EXISTS ${DB_NAME}`);
  await maint.query(`CREATE DATABASE ${DB_NAME}`);
  await maint.end();

  const setup = adminClient(DB_NAME);
  await setup.connect();
  const root = path.join(__dirname, "..", "migrations");
  await setup.query(fs.readFileSync(path.join(root, "005_create_admin_portal.sql"), "utf8"));
  await setup.query(fs.readFileSync(path.join(root, "039_admin_backups.sql"), "utf8"));
  await setup.query(`
    CREATE TABLE synth_patients (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      label text NOT NULL
    );
    CREATE TABLE synth_visits (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      patient_id integer NOT NULL REFERENCES synth_patients(id),
      note text NOT NULL
    );
    INSERT INTO synth_patients (label) VALUES ('Synthetic Patient A');
    INSERT INTO synth_visits (patient_id, note) VALUES (1, 'Synthetic visit');
  `);
  await setup.end();

  const pool = new Pool({
    host: baseEnv.DB_HOST,
    port: Number(baseEnv.DB_PORT),
    user: baseEnv.DB_USER,
    password: baseEnv.DB_PASSWORD,
    database: DB_NAME,
  });
  pool.on("error", () => {});
  await applyAdminBackupSchema(pool);
  const service = createBackupRecoveryService({ db: pool, env: baseEnv });
  const actor = { id: "admin-test", first_name: "Backup", last_name: "Admin", email: "backup-admin@example.test" };

  const created = await service.createPostgresDump({ actor });
  assert.equal(created.status, "success");
  assert.equal(created.archiveFormat, "pg_dump_custom");
  assert.equal(created.recoveryStage, "backup_created");
  assert.equal(created.formatLabel, ".dump");
  assert.ok(created.byteSize > 0);
  assert.equal(created.checksumSha256.length, 64);
  assert.match(created.fileName, /\.dump$/);
  assert.notEqual(created.recoveryStage, "test_restore_passed");

  const stored = await service.getBackupRow(created.id, { includePayload: true });
  const dumpPath = path.join(os.tmpdir(), "dentasync-synthetic.dump");
  fs.writeFileSync(dumpPath, stored.payload, { mode: 0o600 });
  assert.equal(stored.payload.subarray(0, 5).toString("utf8"), "PGDMP");

  const validated = await service.validateBackup({ backupId: created.id, actor });
  assert.equal(validated.recoveryStage, "archive_validated");
  assert.equal(validated.stageLabel, "Archive validated");
  assert.equal(validated.restored, false);
  const afterValidate = await service.getBackupRow(created.id);
  assert.equal(afterValidate.recovery_stage, "archive_validated");
  assert.equal(afterValidate.verified_at, null);

  const tested = await service.testRestorePostgresDump({ backupId: created.id, actor });
  assert.equal(tested.stageLabel, "Test restore passed");
  assert.equal(tested.productionTouched, false);
  assert.ok(tested.tableCount >= 2);
  assert.ok(tested.foreignKeyCount >= 1);
  const afterTest = await service.getBackupRow(created.id);
  assert.equal(afterTest.recovery_stage, "test_restore_passed");
  const live = await pool.query("SELECT label FROM synth_patients");
  assert.deepEqual(live.rows.map((row) => row.label), ["Synthetic Patient A"]);

  const corrupt = Buffer.from(stored.payload);
  corrupt[0] = 0;
  await pool.query("UPDATE admin_portal_backups SET payload = $2 WHERE id = $1", [created.id, corrupt]);
  await assert.rejects(
    () => service.validateBackup({ backupId: created.id, actor }),
    /checksum|could not read/i
  );
  await pool.query(
    "UPDATE admin_portal_backups SET payload = $2, checksum_sha256 = $3 WHERE id = $1",
    [created.id, corrupt, require("node:crypto").createHash("sha256").update(corrupt).digest("hex")]
  );
  await assert.rejects(
    () => service.validateBackup({ backupId: created.id, actor }),
    /could not read/i
  );
  const stillThere = await pool.query("SELECT label FROM synth_patients");
  assert.deepEqual(stillThere.rows.map((row) => row.label), ["Synthetic Patient A"]);
  await pool.query(
    "UPDATE admin_portal_backups SET payload = $2, checksum_sha256 = $3, recovery_stage = 'test_restore_passed' WHERE id = $1",
    [created.id, stored.payload, created.checksumSha256]
  );

  assert.throws(
    () => assertSeparateDatabase(baseEnv, DB_NAME),
    /live application database/
  );

  const blocked = createBackupRecoveryService({ db: pool, env: baseEnv });
  await pool.query("UPDATE synth_patients SET label = 'Changed label'");
  await assert.rejects(
    () => blocked.restoreBackup({
      backupId: created.id,
      confirmation: "RESTORE",
      actor,
      mode: "production",
    }),
    (error) => error.status === 403
  );
  await assert.rejects(
    () => createBackupRecoveryService({
      db: pool,
      env: { ...baseEnv, BACKUP_ALLOW_PRODUCTION_RESTORE: "true" },
    }).restoreBackup({
      backupId: created.id,
      confirmation: "NO",
      actor,
      mode: "production",
    }),
    (error) => error.status === 400
  );
  const unchanged = await pool.query("SELECT label FROM synth_patients");
  assert.deepEqual(unchanged.rows.map((row) => row.label), ["Changed label"]);

  const restored = await createBackupRecoveryService({
    db: pool,
    env: { ...baseEnv, BACKUP_ALLOW_PRODUCTION_RESTORE: "true" },
  }).restoreBackup({
    backupId: created.id,
    confirmation: "RESTORE",
    actor,
    mode: "production",
  });
  assert.equal(restored.restored, true);
  assert.ok(restored.safetyBackup?.id);
  const recovered = await pool.query("SELECT label FROM synth_patients ORDER BY id");
  assert.deepEqual(recovered.rows.map((row) => row.label), ["Synthetic Patient A"]);
  const safety = await pool.query(
    "SELECT COUNT(*)::int AS count FROM admin_portal_backups WHERE backup_type = 'safety' AND status = 'success'"
  );
  assert.ok(safety.rows[0].count >= 1);

  const legacy = await service.createBackup({ type: "manual", actor, notes: "Synthetic legacy snapshot" });
  assert.match(legacy.fileName, /\.dsb$/);
  const legacyCheck = await service.validateBackup({ backupId: legacy.id, actor });
  assert.equal(legacyCheck.valid, true);
  assert.ok(legacyCheck.tableCount >= 2);

  const blind = createBackupRecoveryService({
    db: pool,
    env: { ...baseEnv, PATH: path.join(os.tmpdir(), "dentasync-no-pg-tools") },
  });
  await assert.rejects(
    () => blind.createPostgresDump({ actor }),
    /pg_dump and pg_restore/
  );
  const failed = await pool.query(
    "SELECT error_detail FROM admin_portal_backups WHERE status = 'failed' ORDER BY created_at DESC LIMIT 1"
  );
  assert.match(failed.rows[0].error_detail, /pg_dump and pg_restore/);
  assert.doesNotMatch(failed.rows[0].error_detail, /Synthetic Patient A|postgres:\/\//i);

  fs.rmSync(dumpPath, { force: true });
  await pool.end();
});
